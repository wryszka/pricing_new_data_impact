# MAGIC %md
# MAGIC ## 4. Train GBM — Model 1 (Standard Features)
# MAGIC
# MAGIC We use LightGBM with a **Gamma objective** — appropriate for severity because
# MAGIC claim costs are strictly positive and right-skewed.

# COMMAND ----------

lgb_params = {
    "objective": "gamma",
    "metric": "gamma_deviance",
    "learning_rate": 0.05,
    "num_leaves": 31,
    "min_child_samples": 50,
    "subsample": 0.8,
    "colsample_bytree": 0.8,
    "verbose": -1,
    "seed": 42,
}

# --- Model 1: Standard ---
ds_train_std = lgb.Dataset(train_df[standard_features], label=train_df[target])
ds_val_std = lgb.Dataset(test_df[standard_features], label=test_df[target], reference=ds_train_std)

print("Training Model 1 (Standard features)...")
model_std = lgb.train(
    lgb_params,
    ds_train_std,
    num_boost_round=500,
    valid_sets=[ds_val_std],
    callbacks=[lgb.log_evaluation(100), lgb.early_stopping(50)],
)

pred_std = model_std.predict(test_df[standard_features])
metrics_std = evaluate_model(test_df[target].values, pred_std, "Standard")
print(f"  MAE: £{metrics_std['mae']:,.0f} | RMSE: £{metrics_std['rmse']:,.0f} | Gini: {metrics_std['gini']:.4f}")

# COMMAND ----------

# MAGIC %md
# MAGIC ## 5. Train GBM — Model 2 (Enriched Features)

# COMMAND ----------

# --- Model 2: Enriched ---
ds_train_enr = lgb.Dataset(train_df[enriched_features], label=train_df[target])
ds_val_enr = lgb.Dataset(test_df[enriched_features], label=test_df[target], reference=ds_train_enr)

print("Training Model 2 (Enriched features)...")
model_enr = lgb.train(
    lgb_params,
    ds_train_enr,
    num_boost_round=500,
    valid_sets=[ds_val_enr],
    callbacks=[lgb.log_evaluation(100), lgb.early_stopping(50)],
)

pred_enr = model_enr.predict(test_df[enriched_features])
metrics_enr = evaluate_model(test_df[target].values, pred_enr, "Enriched")
print(f"  MAE: £{metrics_enr['mae']:,.0f} | RMSE: £{metrics_enr['rmse']:,.0f} | Gini: {metrics_enr['gini']:.4f}")

