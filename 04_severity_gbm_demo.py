# MAGIC %md
# MAGIC ## 2. Train / Test Split & Feature Sets

# COMMAND ----------

standard_features = [
    "building_age", "bedrooms", "sum_insured", "prior_claims", "policy_tenure",
    "property_type_flat", "property_type_semi_detached", "property_type_terraced",
    "construction_other", "construction_stone", "construction_timber",
    "occupancy_tenant",
]

enriched_features = standard_features + [
    "flood_risk_zone", "crime_index", "distance_fire_station_km",
    "annual_rainfall_mm", "subsidence_risk",
]

target = "claim_severity"

train_df, test_df = train_test_split(claimants, test_size=0.3, random_state=42)
print(f"Train: {len(train_df):,} | Test: {len(test_df):,}")

# Save severity train/test splits to UC
spark.createDataFrame(train_df).write.mode("overwrite").saveAsTable(f"{CATALOG}.{SCHEMA}.severity_train_set")
spark.createDataFrame(test_df).write.mode("overwrite").saveAsTable(f"{CATALOG}.{SCHEMA}.severity_test_set")

