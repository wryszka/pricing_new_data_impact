# Load the frequency-priced portfolio (test set from notebook 01)
priced = spark.table(f"{CATALOG}.{SCHEMA}.priced_portfolio").toPandas()

# Predict severity for ALL test policies (not just claimants)
sev_pred_std = model_std.predict(priced[standard_features])
sev_pred_enr = model_enr.predict(priced[enriched_features])

expense_load = 1.35

# Full quotes: frequency × severity × expense load
priced["sev_pred_standard"] = sev_pred_std
priced["sev_pred_enriched"] = sev_pred_enr
priced["full_quote_standard"] = np.round(priced["pred_freq_standard"] * sev_pred_std * expense_load, 2)
priced["full_quote_enriched"] = np.round(priced["pred_freq_enriched"] * sev_pred_enr * expense_load, 2)

# Save
spark.createDataFrame(priced).write.mode("overwrite").saveAsTable(f"{CATALOG}.{SCHEMA}.severity_priced_portfolio")

print(f"Avg full quote (standard): £{priced['full_quote_standard'].mean():.2f}")
print(f"Avg full quote (enriched): £{priced['full_quote_enriched'].mean():.2f}")
print(f"Avg actual loss:           £{priced['actual_loss'].mean():.2f}")

display(spark.table(f"{CATALOG}.{SCHEMA}.severity_priced_portfolio").select(
    "building_age", "bedrooms", "flood_risk_zone", "subsidence_risk",
    "full_quote_standard", "full_quote_enriched", "actual_loss"
).limit(20))

# COMMAND ----------

# Loss ratio by decile — using full quotes
lr_rows = []
for model_name, quote_col in [("Standard", "full_quote_standard"), ("Enriched", "full_quote_enriched")]:
    temp = priced.copy()
    temp["decile"] = pd.qcut(temp[quote_col], 10, labels=False, duplicates="drop")
    grouped = temp.groupby("decile").agg(
        total_premium=(quote_col, "sum"),
        total_loss=("actual_loss", "sum"),
        policy_count=("actual_loss", "count"),
    ).reset_index()
    grouped["loss_ratio"] = grouped["total_loss"] / grouped["total_premium"]
    grouped["model"] = model_name
    lr_rows.append(grouped)

lr_all = pd.concat(lr_rows)
spark.createDataFrame(lr_all).write.mode("overwrite").saveAsTable(f"{CATALOG}.{SCHEMA}.severity_loss_ratio_by_decile")

fig, ax = plt.subplots(figsize=(10, 5))
for model, color in [("Standard", "#E53935"), ("Enriched", "#43A047")]:
    subset = lr_all[lr_all["model"] == model]
    ax.plot(subset["decile"], subset["loss_ratio"], marker="o", label=model, color=color, linewidth=2)
ax.axhline(y=1.0, color="grey", linestyle="--", alpha=0.5, label="Breakeven (LR=1)")
ax.set_xlabel("Premium Decile (cheapest → most expensive)")
ax.set_ylabel("Loss Ratio")
ax.set_title("Loss Ratio by Full Quote Decile — Freq×Sev Standard vs Enriched")
ax.legend()
plt.tight_layout()
plt.show()

